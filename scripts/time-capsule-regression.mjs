import fs from 'node:fs';
import assert from 'node:assert/strict';

const html = fs.readFileSync('index.html', 'utf8');
const start = html.indexOf('/* time-capsule:start */');
const end = html.indexOf('/* time-capsule:end */');
assert.ok(start >= 0 && end > start, 'time capsule pure-function block missing');
const block = html.slice(start, end).replace(/\/\* time-capsule:start \*\//, '');
const vm = await import('node:vm');
const ctx = { console, Date, Math, String, Number, Array, Object, JSON };
vm.runInNewContext(block, ctx);
const { parseTimeCapsuleTag, stripTimeCapsuleTags, capsuleState, capsuleCountdown, applyTimeCapsuleTag } = ctx;
assert.equal(JSON.stringify(parseTimeCapsuleTag('[胶囊:给未来的我|2099-01-02T03:04|那时再看这句话]')), JSON.stringify({ title: '给未来的我', openAt: '2099-01-02T03:04', body: '那时再看这句话' }));
assert.equal(stripTimeCapsuleTags('前文\n[胶囊:标题|2099-01-02T03:04|秘密]\n后文'), '前文\n\n后文');
assert.equal(stripTimeCapsuleTags('[胶囊:标题|2099-01-02T03:04|秘密', true), '');
assert.equal(capsuleState({ openAt: '2099-01-02T03:04' }, new Date('2099-01-02T03:03:59')), 'sealed');
assert.equal(capsuleState({ openAt: '2099-01-02T03:04' }, new Date('2099-01-02T03:04:00')), 'open');
assert.match(capsuleCountdown({ openAt: '2099-01-02T03:04' }, new Date('2099-01-02T03:03:59')), /还有/);
assert.equal(capsuleCountdown({ openAt: '2099-01-02T03:04' }, new Date('2099-01-02T03:04:00')), '可以拆封了');
const role = { timeCapsules: [] };
const applied = applyTimeCapsuleTag('[胶囊:他写给未来的你|2099-01-02T03:04|到时候记得打开]', role, 'character', 'm1', new Date('2026-01-01T00:00:00'));
assert.equal(applied.text, '');
assert.equal(role.timeCapsules.length, 1);
assert.equal(role.timeCapsules[0].author, 'character');
assert.equal(role.timeCapsules[0].body, '到时候记得打开');
assert.ok(role.timeCapsules[0].id && role.timeCapsules[0].createdAt);
const guestRole = { timeCapsules: [] };
assert.equal(applyTimeCapsuleTag('[胶囊:不该写入|2099-01-02T03:04|客人段]', guestRole, 'guest', 'm2', Date.now()).text, '[胶囊:不该写入|2099-01-02T03:04|客人段]');
assert.equal(guestRole.timeCapsules.length, 0);
assert.match(html, /pushTimeCapsule\(.*openAt/s);
assert.match(html, /timeCapsules/);
assert.match(html, /const SYNCED_KEYS = \[[\s\S]*?"roles"/);
const sw = fs.readFileSync('sw.js', 'utf8');
assert.match(sw, /role-chat-cache-v424/);
console.log('time capsule regression: ok');
// v420 回归：胶囊提示词不能引用块内 const selfCardRole（iPhone 报 Can't find variable: selfCardRole，主聊天发不出）
assert.ok(!/buildTimeCapsulePrompt\(selfCardRole\)/.test(html), 'time capsule prompt must not reference block-scoped selfCardRole');
assert.match(html, /buildTimeCapsulePrompt\(selfCardRoleFor\(currentConv\(\)\)\)/);
