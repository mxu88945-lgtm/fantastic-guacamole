import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const html = fs.readFileSync('index.html', 'utf8');
const start = html.indexOf('/* bedside-nudge:start */');
const end = html.indexOf('/* bedside-nudge:end */');
assert.ok(start >= 0 && end > start, 'bedside nudge pure-function block missing');
const code = html.slice(start, end).replace('/* bedside-nudge:start */', '');
const ctx = { console, Date, Math, String, Number, Array, Object, JSON };
vm.runInNewContext(code, ctx);
const { parseBedsideNudgeTag, stripBedsideNudgeTags, chooseBedsideNudge, applyBedsideNudgeReply, bedsideNudgePrompt } = ctx;
ctx.Math.random = () => 0;
assert.equal(JSON.stringify(parseBedsideNudgeTag('[戳一戳:困倦|早点睡，别硬撑]')), JSON.stringify({ kind: 'sleepy', text: '早点睡，别硬撑' }));
assert.equal(stripBedsideNudgeTags('嗯。\n[戳一戳:喝水|记得喝水呀]'), '嗯。');
assert.equal(stripBedsideNudgeTags('嗯。[戳一', true), '嗯。');
assert.equal(chooseBedsideNudge([], { energy: 20, sleepy: 80 }).text, '别硬撑啦，去躺一会儿。');
assert.equal(chooseBedsideNudge([{ kind: 'low', text: '喝口温水。' }], { energy: 20, sleepy: 20 }).text, '喝口温水。');
const role = { bedsideNotes: [] };
const result = applyBedsideNudgeReply('[戳一戳:default|看到这条就戳我一下]', role, true);
assert.equal(result.text, '');
assert.equal(role.bedsideNotes.length, 1);
assert.equal(role.bedsideNotes[0].text, '看到这条就戳我一下');
const guestRole = { bedsideNotes: [] };
assert.equal(applyBedsideNudgeReply('[戳一戳:default|客人不该存]', guestRole, false).text, '');
assert.equal(guestRole.bedsideNotes.length, 0);
assert.match(bedsideNudgePrompt(true), /戳一戳/);
assert.equal(bedsideNudgePrompt(false), '');
assert.match(html, /bedsideNudgePending/);
assert.match(html, /id="bedside-nudge-btn"/);
const sw = fs.readFileSync('sw.js', 'utf8');
assert.match(sw, /role-chat-cache-v437/);
console.log('bedside nudge regression: ok');
